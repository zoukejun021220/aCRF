"""Build and verify immutable local snapshots of the pinned public COSMoS exports."""

import hashlib
import json
import tempfile
from pathlib import Path

from .catalog import CosmosCatalog
from .source import COMMIT, FILES, HASHES, REPOSITORY, parse_export

DEFAULT_SNAPSHOT = Path(__file__).resolve().parents[2] / "kb" / "cosmos" / COMMIT
NOTICE = f"""# COSMoS metadata snapshot

Source: [{REPOSITORY}]({REPOSITORY}), commit `{COMMIT}`.

Content based on COSMoS (GitHub), used under the
[CC-BY-4.0 license](https://creativecommons.org/licenses/by/4.0/).
Retain this attribution and identify changes when redistributing derived content.
The raw CSV files and upstream README are unmodified. The local manifest,
grouping and unresolved-reference report were generated by the aCRF importer.
Upstream code/scripts use MIT; that license does not replace the content license.
The original upstream README and LICENSE are retained under `raw/`.

BC and SDTM exports are published content. CRF specializations are DRAFT and
are excluded by default. Package dates are preserved per record; this snapshot
is not a claim that every record was newly released on the same date.

Source references outside a specialization's variables are reported in
`issues.json`. These can be cross-domain references or source inconsistencies;
they are not automatically errors, and the importer never repairs them by guess.

Verify locally with:

```sh
python3 -m sdtm_knowledge_base.cosmos verify
```
"""


def json_bytes(value: dict | list) -> bytes:
    """Serialize derived artifacts deterministically; never insert clocks or paths."""
    return (
        json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    ).encode("utf-8")


def _verified_source(source: Path) -> tuple[dict[str, bytes], CosmosCatalog]:
    """Read exact pinned files and validate their hashes before marking records verified."""
    contents = {}
    for name, expected in HASHES.items():
        try:
            content = (source / name).read_bytes()
        except OSError as exc:
            raise ValueError(
                f"Cannot read required COSMoS source file: {name}"
            ) from exc
        if hashlib.sha256(content).hexdigest() != expected:
            raise ValueError(f"COSMoS source hash mismatch: {name}")
        contents[name] = content
    records = tuple(
        record
        for kind, name in FILES.items()
        for record in parse_export(kind, contents[name], verified=True)
    )
    return contents, CosmosCatalog(records)


def _derived_files(catalog: CosmosCatalog) -> dict[str, bytes]:
    """Produce counts, source attribution and unresolved references from verified data."""
    manifest = {
        "schema_version": 1,
        "repository": REPOSITORY,
        "commit": COMMIT,
        "content_license": "CC-BY-4.0",
        "upstream_code_license": "MIT",
        "default_filters": {"include_drafts": False, "sdtmig_version": "3.4"},
        "files": [
            {
                "path": f"raw/{name}",
                "upstream_path": name,
                "sha256": digest,
                "url": f"{REPOSITORY}/blob/{COMMIT}/{name}",
            }
            for name, digest in sorted(HASHES.items())
        ],
        **catalog.summary(),
    }
    return {
        "manifest.json": json_bytes(manifest),
        "issues.json": json_bytes(catalog.issues()),
        "README.md": NOTICE.encode("utf-8"),
    }


def build_snapshot(
    source_directory: Path, output_directory: Path = DEFAULT_SNAPSHOT
) -> CosmosCatalog:
    """Import already downloaded public files atomically; refuse existing destinations."""
    source, output = Path(source_directory), Path(output_directory)
    if output.exists():
        raise FileExistsError(f"Snapshot destination already exists: {output}")
    contents, catalog = _verified_source(source)
    derived = _derived_files(catalog)
    # Verify all input before publishing a directory that consumers could discover.
    try:
        output.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(
            prefix=".cosmos-", dir=output.parent
        ) as temporary:
            staged = Path(temporary) / "snapshot"
            for name, content in {
                **{f"raw/{name}": data for name, data in contents.items()},
                **derived,
            }.items():
                destination = staged / name
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(content)
            if output.exists():
                raise FileExistsError(f"Snapshot destination already exists: {output}")
            staged.rename(output)
    except OSError as exc:
        raise OSError(f"Cannot publish COSMoS snapshot at {output}: {exc}") from exc
    return catalog


def load_snapshot(directory: Path = DEFAULT_SNAPSHOT) -> CosmosCatalog:
    """Verify source bytes and derived manifests before exposing a local snapshot."""
    directory = Path(directory)
    _, catalog = _verified_source(directory / "raw")
    for name, expected in _derived_files(catalog).items():
        try:
            actual = (directory / name).read_bytes()
        except OSError as exc:
            raise ValueError(f"Missing COSMoS snapshot artifact: {name}") from exc
        if actual != expected:
            raise ValueError(
                f"COSMoS snapshot artifact differs from verified source: {name}"
            )
    return catalog
